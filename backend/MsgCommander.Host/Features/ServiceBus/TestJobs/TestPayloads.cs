using System.Text.Json;
using MsgCommander.Contracts.ServiceBus.TestJobs;
using MsgCommander.Domain.ServiceBus.TestJobs;
using DomainPayloads = MsgCommander.Domain.ServiceBus.TestJobs.TestPayloads;

namespace MsgCommander.Host;

internal static class TestPayloads
{
	private const int GeneratedLimit = DomainPayloads.GeneratedLimit;
	private static readonly TestGenerator Default = new("literal", 1, 1024);
	private static OperationException Invalid() => new(OperationFailure.InvalidInput, "Invalid test payload. Use literal text, a JSON template with {{index}}, {{jobId}}, {{messageId}}, {{seed}} or {{random}}, or 1–65536 generated bytes. Generated output is limited to 64 KiB.");
	public static TestGenerator Read(JsonElement input)
	{
		if (!input.TryGetProperty("generator", out var value))
			return Default;
		if (value.ValueKind != JsonValueKind.Object || value.EnumerateObject().Count() != 3 || value.EnumerateObject().Any(p => p.Name is not ("kind" or "seed" or "sizeBytes")))
			throw Invalid();
		if (!value.TryGetProperty("kind", out var k) || k.ValueKind != JsonValueKind.String || !value.TryGetProperty("seed", out var s) || s.ValueKind != JsonValueKind.Number || !s.TryGetInt32(out var seed) || !value.TryGetProperty("sizeBytes", out var b) || b.ValueKind != JsonValueKind.Number || !b.TryGetInt32(out var size))
			throw Invalid();
		var kind = k.GetString();
		if (kind is not ("literal" or "json-template" or "binary") || seed < 0 || size is < 1 or > GeneratedLimit)
			throw Invalid();
		return new(kind, seed, size);
	}

	public static object Preview(JsonElement input, CancellationToken token)
	{
		if (input.ValueKind != JsonValueKind.Object || input.EnumerateObject().Any(p => p.Name is not ("id" or "generator" or "body" or "contentType" or "sampleIndex")))
			throw Invalid();
		var id = input.GetProperty("id").GetString()!;
		var index = input.GetProperty("sampleIndex").GetInt32();
		if (!Guid.TryParse(id, out _) || index is < 1 or > 100000)
			throw Invalid();
		var generator = Read(input);
		var body = input.GetProperty("body").GetString()!;
		var contentType = input.GetProperty("contentType").GetString()!;
		return TestPayloadPreviewService.Preview(id, index, generator, body, contentType, token);
	}
}
