using MsgCommander.Application.Common;
using MsgCommander.Contracts.ServiceBus.TestJobs;
using MsgCommander.Domain.ServiceBus.TestJobs;
using DomainPayloads = MsgCommander.Domain.ServiceBus.TestJobs.TestPayloads;

namespace MsgCommander.Application.ServiceBus.TestJobs;

public static class TestPayloadPreviewService
{
	public static TestPayloadPreviewResult Preview(string id, int index, TestGenerator generator, string body, string contentType, CancellationToken token)
	{
		if (!Guid.TryParse(id, out _) || index is < 1 or > 100000)
			throw new OperationException(OperationFailure.InvalidInput, "Invalid test payload. Use literal text, a JSON template with {{index}}, {{jobId}}, {{messageId}}, {{seed}} or {{random}}, or 1–65536 generated bytes. Generated output is limited to 64 KiB.");
		try
		{
			var definition = new PayloadGenerator(generator.Kind, generator.Seed, generator.SizeBytes);
			DomainPayloads.Validate(definition, body, contentType);
			var payload = DomainPayloads.Create(definition, body, contentType, id, index, token);
			return new(Convert.ToBase64String(payload.Body), payload.ContentType, payload.Body.Length, index);
		}
		catch (TestJobRuleException error)
		{
			throw new OperationException(OperationFailure.InvalidInput, error.Message);
		}
	}
}
