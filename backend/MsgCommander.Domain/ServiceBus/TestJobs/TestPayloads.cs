using System.Buffers.Binary;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace MsgCommander.Domain.ServiceBus.TestJobs;

public sealed record PayloadGenerator(string Kind, int Seed, int SizeBytes);
public sealed record TestPayload(byte[] Body, string ContentType);
public static partial class TestPayloads
{
	public const int GeneratedLimit = 65536;
	public static readonly PayloadGenerator Default = new("literal", 1, 1024);
	private static TestJobRuleException Invalid() => new("Invalid test payload. Use literal text, a JSON template with {{index}}, {{jobId}}, {{messageId}}, {{seed}} or {{random}}, or 1–65536 generated bytes. Generated output is limited to 64 KiB.");
	[GeneratedRegex(@"\{\{([^{}]+)\}\}")]
	private static partial Regex Tokens();
	private static byte[] Block(PayloadGenerator generator, int index, int block) => SHA256.HashData(Encoding.ASCII.GetBytes(
		FormattableString.Invariant($"{generator.Seed}:{index}:{block}")));
	public static void Validate(PayloadGenerator generator, string body, string contentType)
	{
		if (generator.Kind is not ("literal" or "json-template" or "binary") || generator.Seed < 0 || generator.SizeBytes is < 1 or > GeneratedLimit)
			throw Invalid();
		if (body is null || contentType is null || body.Length > 65536 || contentType.Length > 128 || (generator.Kind == "binary" && body.Length > 0) ||
			(generator.Kind != "literal" && contentType.Length > 0))
			throw Invalid();
		if (generator.Kind == "json-template")
		{
			// Preflight the widest numeric substitutions before any sender is opened.
			Create(generator, body, contentType, Guid.Empty.ToString(), 100000, CancellationToken.None, true);
		}
	}
	public static TestPayload Create(PayloadGenerator generator, string body, string contentType, string jobId, int index,
		CancellationToken token, bool widest = false)
	{
		token.ThrowIfCancellationRequested();
		if (generator.Kind == "literal")
			return new(Encoding.UTF8.GetBytes(body), contentType);
		if (generator.Kind == "binary")
		{
			var bytes = new byte[generator.SizeBytes];
			for (var offset = 0; offset < bytes.Length; offset += 32)
			{
				token.ThrowIfCancellationRequested();
				var block = Block(generator, index, offset / 32);
				block.AsSpan(0, Math.Min(32, bytes.Length - offset)).CopyTo(bytes.AsSpan(offset));
			}
			return new(bytes, "application/octet-stream");
		}
		var random = widest ? uint.MaxValue : BinaryPrimitives.ReadUInt32BigEndian(Block(generator, index, 0));
		var text = Tokens().Replace(body, match => match.Groups[1].Value.Trim() switch
		{
			"index" => index.ToString(CultureInfo.InvariantCulture),
			"jobId" => jobId,
			"messageId" => $"{jobId}-{index}",
			"seed" => generator.Seed.ToString(CultureInfo.InvariantCulture),
			"random" => random.ToString(CultureInfo.InvariantCulture),
			_ => throw Invalid()
		});
		if (text.Contains("{{", StringComparison.Ordinal) || Encoding.UTF8.GetByteCount(text) > GeneratedLimit)
			throw Invalid();
		try
		{
			using var document = JsonDocument.Parse(text, new()
			{
				MaxDepth = 32
			});
		}
		catch (JsonException) { throw Invalid(); }
		return new(Encoding.UTF8.GetBytes(text), "application/json");
	}
}
